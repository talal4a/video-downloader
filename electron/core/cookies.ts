// Convert browser cookies (from Electron's session) into the Netscape cookies.txt format yt-dlp reads.

export interface CookieLike {
  name: string;
  value: string;
  domain?: string;
  hostOnly?: boolean;
  path?: string;
  secure?: boolean;
  httpOnly?: boolean;
  expirationDate?: number;
}

export function toNetscapeCookieFile(cookies: CookieLike[]): string {
  const lines = ['# Netscape HTTP Cookie File', '# Generated by Video Downloader. Do not share this file.', ''];
  for (const c of cookies) {
    if (!c.name || !c.domain) continue;
    let domain = c.domain;
    const includeSub = c.hostOnly ? false : true;
    if (includeSub && !domain.startsWith('.')) domain = `.${domain}`;
    if (!includeSub) domain = domain.replace(/^\./, '');
    const prefix = c.httpOnly ? '#HttpOnly_' : '';
    const expiry = c.expirationDate ? Math.floor(c.expirationDate) : 0;
    const value = String(c.value ?? '').replace(/[\r\n\t]/g, '');
    lines.push(
      [
        `${prefix}${domain}`,
        includeSub ? 'TRUE' : 'FALSE',
        c.path || '/',
        c.secure ? 'TRUE' : 'FALSE',
        String(expiry),
        c.name,
        value,
      ].join('\t'),
    );
  }
  return `${lines.join('\n')}\n`;
}
